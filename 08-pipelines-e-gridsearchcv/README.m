# 08 - Pipelines de Machine Learning e Otimização com GridSearchCV

Este laboratório aborda a construção de pipelines robustos de Machine Learning e a automatização do ajuste fino de hiperparâmetros (*hyperparameter tuning*) utilizando **GridSearchCV** e validação cruzada.

---

## 🎯 Objetivos do Laboratório

* Encapsular etapas de pré-processamento e modelagem em uma estrutura única de `Pipeline`.
* Prevenir o vazamento de dados (*data leakage*) durante a transformação e validação dos modelos.
* Aplicar a busca em grade (*GridSearchCV*) para encontrar a combinação ideal de hiperparâmetros.
* Comparar o desempenho dos modelos antes e depois da otimização.

---

## 🛠️ Tecnologias e Bibliotecas

* **Python 3**
* **Scikit-Learn:** Módulos `Pipeline`, `ColumnTransformer`, `GridSearchCV` e `StratifiedKFold`.
* **Pandas & NumPy:** Processamento e manipulação de conjuntos de dados.
* **Matplotlib & Seaborn:** Visualização de resultados.

